import { gzipSync } from "node:zlib";
import { writeFileSync } from "node:fs";

/** Tiny NBT writer used only to generate a deterministic inventory fixture. */
const u16 = (n) => Buffer.from([(n >> 8) & 0xff, n & 0xff]);
const i32 = (n) => {
  const b = Buffer.alloc(4);
  b.writeInt32BE(n);
  return b;
};
const str = (s) => {
  const data = Buffer.from(s, "utf8");
  return Buffer.concat([u16(data.length), data]);
};
const named = (type, name, payload) => Buffer.concat([Buffer.from([type]), str(name), payload]);
const compound = (entries) => Buffer.concat([...entries, Buffer.from([0])]);
const byte = (n) => Buffer.from([n & 0xff]);
const list = (elementType, elements) => Buffer.concat([Buffer.from([elementType]), i32(elements.length), ...elements]);

const item = (id, count, extraId, name) => {
  const tag = compound([
    named(10, "ExtraAttributes", compound([named(8, "id", str(extraId))])),
    named(10, "display", compound([named(8, "Name", str(JSON.stringify({ text: name, color: "gold" }))), named(9, "Lore", list(8, [str("§7A fixture item"), str("§8SkyBlock Companion test")]))])),
  ]);
  return compound([
    named(8, "id", str(id)),
    named(1, "Count", byte(count)),
    named(2, "Damage", Buffer.from([0, 0])),
    named(10, "tag", tag),
  ]);
};

const empty = compound([]);
const root = named(
  10,
  "",
  compound([
    named(9, "i", list(10, [item("minecraft:iron_sword", 1, "HYPERION", "Hyperion"), item("minecraft:diamond", 64, "ENCHANTED_DIAMOND", "Enchanted Diamond"), empty])),
  ]),
);

const base64 = gzipSync(root).toString("base64");

const file = `/**
 * Deterministic fixture for the Hypixel inventory decoder.
 * Generated by scripts/make-inventory-fixture.mjs — do not edit by hand.
 *
 * Contains a 3-slot inventory: Hyperion, 64x Enchanted Diamond, empty slot.
 */
export const INVENTORY_FIXTURE_BASE64 =
  "${base64}";
`;

writeFileSync(new URL("../src/utils/__fixtures__/inventory-fixture.ts", import.meta.url), file);
console.log("fixture written, bytes:", base64.length);
